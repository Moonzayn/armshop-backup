import { createContext, useContext, useEffect, useState, type ReactNode } from "react";

/* ------------------------------------------------------------------ */
/*  Bilingual UI (Indonesian default, English switchable).             */
/*  Components write copy in Indonesian and wrap it in t("..."); the   */
/*  EN dictionary below maps those exact strings to English.           */
/* ------------------------------------------------------------------ */

export type Lang = "id" | "en";

const stored = (() => {
  try {
    return localStorage.getItem("lcs_lang") as Lang | null;
  } catch {
    return null;
  }
})();

let current: Lang = stored === "en" ? "en" : "id";

export function getLang(): Lang {
  return current;
}

export function tr(text: string, vars?: Record<string, string | number>): string {
  let out = current === "en" ? (EN[text] ?? text) : text;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.split(`{${k}}`).join(String(v));
    }
  }
  return out;
}

interface LangCtxValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: typeof tr;
}

const LangCtx = createContext<LangCtxValue>({ lang: current, setLang: () => {}, t: tr });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(current);
  const setLang = (l: Lang) => {
    current = l;
    try {
      localStorage.setItem("lcs_lang", l);
    } catch {
      /* ignore */
    }
    setLangState(l);
  };
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return <LangCtx.Provider value={{ lang, setLang, t: tr }}>{children}</LangCtx.Provider>;
}

export function useLang(): LangCtxValue {
  return useContext(LangCtx);
}

